"""Phase H9 sweep files, generated mechanically from the Phase H8 evaluation sweeps.

Each H8 evaluation sweep (``fedastro select ... --eval-seeds``) holds one arm's winner for one
model family, chosen on validation scores only (PREREG.md section 5). This module adds the H9
settings fixed in PREREG.md section 6 on top of that winner, so no H9 setting is chosen by hand:

- ``h9_<dataset>_<family>_<arm>``: the arm at every shift setting in ``SHIFT_SETTINGS``
  (location shift SIMULATED); the hierarchical arm also with simulated secure aggregation, which
  changes no number, only overhead.
- ``h9_<dataset>_<family>_full``: the full architecture at the primary shift (simulated links
  with loss of signal, secure aggregation, the update gate, test-then-train); the mission
  scenario, never used for H1-H4.
- ``h9_<dataset>_<family>_stream``: the test-then-train sensitivity grid at the primary shift.
- ``configs/hypotheses/h9_<dataset>.yaml``: the spec ``fedastro hypotheses`` reads.

The files are written to ``configs/sweeps/`` and committed (with PREREG section 6) before any H9
run. Generated: regenerate instead of editing.
"""

from __future__ import annotations

import os
from pathlib import Path
from typing import Any

import yaml

from fedastro.grid import load_grid

SHIFT_SETTINGS: tuple[tuple[str, float], ...] = (
    ("both", 0.0), ("both", 0.5), ("both", 1.0), ("both", 2.0), ("covariate", 1.0), ("concept", 1.0))
PRIMARY_SHIFT = ("both", 1.0)
SHIFTED_REGIONS = ("moon", "mars")  # LEO is the unshifted reference (PREREG section 3)
EVAL_SEEDS = (0, 1, 2, 3, 4)
ARMS_OF = {("centralized",): "centralized", ("local_only",): "local_only", ("federated",): "federated",
           ("local_only", "hierarchical"): "hierarchical"}
STREAM_ARMS = ["local_only", "hierarchical", "hierarchical_stream"]
# Full architecture (scenario assumptions, PREREG section 6): Mars mean preset, loss of signal on,
# a node whose update is not at its regional aggregator 120 simulated s after the round starts
# misses the round (as in the Phase H3/H4 smoke configs).
FULL = {"comms.enabled": True, "comms.preset": "mars_mean", "comms.los": True,
        "hier_fl.region_deadline_s": 120.0, "secagg.enabled": True, "updates.enabled": True}
STREAM_GRID = {"stream.label_fraction": [0.1, 1.0], "stream.label_delay_rounds": [0, 1]}


def _shift(kind: str, magnitude: float) -> dict[str, Any]:
    return {"shift.enabled": True, "shift.kind": kind, "shift.magnitude": magnitude}


def _winner(eval_sweep: Path) -> tuple[str, str, Path, dict[str, Any]]:
    """(family, arm, base path, the winner's overrides) of one H8 evaluation sweep."""
    spec = yaml.safe_load(eval_sweep.read_text())
    _, variants = load_grid(eval_sweep)
    if len(variants) != 1 or not spec.get("variants"):
        raise ValueError(f"{eval_sweep}: not an evaluation sweep (one variant expected)")
    cfg = variants[0].config
    arm = ARMS_OF.get(tuple(cfg.arms))
    if arm is None:
        raise ValueError(f"{eval_sweep}: arms {list(cfg.arms)} are not one evaluated arm")
    over = {**(spec.get("fixed") or {}), **spec["variants"][0]}
    over.pop("arms", None)
    return cfg.model.arch, arm, (eval_sweep.parent / spec["base"]).resolve(), over


def _write(path: Path, name: str, base: Path, fixed: dict[str, Any], source: str,
           variants: list[dict[str, Any]] | None = None, axes: dict[str, list] | None = None) -> Path:
    out: dict[str, Any] = {"name": name, "base": os.path.relpath(base, path.parent.resolve()),
                           "seeds": list(EVAL_SEEDS), "fixed": fixed}
    if variants is not None:
        out["variants"] = variants
    if axes is not None:
        out["axes"] = axes
    header = (f"# GENERATED by `fedastro h9-sweeps` from {source} (Phase H8 winner, validation only).\n"
              f"# PREREG.md section 6. Location shift SIMULATED. Do not edit by hand; regenerate instead.\n")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(header + yaml.safe_dump(out, sort_keys=False))
    load_grid(path)  # must load
    return path


def emit_h9_sweeps(eval_sweeps: list[Path], out_dir: Path, dataset: str,
                   spec_dir: Path | None = None) -> list[Path]:
    winners: dict[str, dict[str, tuple[Path, dict[str, Any], str]]] = {}
    for p in eval_sweeps:
        fam, arm, base, over = _winner(p)
        if arm in winners.setdefault(fam, {}):
            raise ValueError(f"two evaluation sweeps for {fam} / {arm}: {winners[fam][arm][2]}, {p.name}")
        winners[fam][arm] = (base, over, p.name)
    need = {"centralized", "local_only", "federated", "hierarchical"}
    for fam, arms in winners.items():
        if set(arms) != need:
            raise ValueError(f"{fam}: have arms {sorted(arms)}, need {sorted(need)}")
    written, spec = [], {"dataset": dataset, "primary_shift": {"kind": PRIMARY_SHIFT[0], "magnitude": PRIMARY_SHIFT[1]},
                         "shifted_regions": list(SHIFTED_REGIONS), "families": {}}
    for fam, arms in sorted(winners.items()):
        spec["families"][fam] = {}
        for arm, (base, over, src) in arms.items():
            name = f"h9_{dataset}_{fam}_{arm}"
            run_arms = [arm] if arm != "hierarchical" else ["local_only", "hierarchical"]
            fixed = {**over, "arms": run_arms, **({"secagg.enabled": True} if arm == "hierarchical" else {})}
            written.append(_write(out_dir / f"{name}.yaml", name, base, fixed, src,
                                  variants=[_shift(k, m) for k, m in SHIFT_SETTINGS]))
            spec["families"][fam][arm] = f"{name}.yaml"
        base, over, src = arms["hierarchical"]
        fixed = {**over, "arms": STREAM_ARMS, **_shift(*PRIMARY_SHIFT)}
        name = f"h9_{dataset}_{fam}_full"
        written.append(_write(out_dir / f"{name}.yaml", name, base, fixed, src, variants=[dict(FULL)]))
        name = f"h9_{dataset}_{fam}_stream"
        written.append(_write(out_dir / f"{name}.yaml", name, base, {**fixed, "secagg.enabled": True}, src,
                              axes=STREAM_GRID))
    # Not in configs/sweeps/: every file there must be a runnable sweep (scripts/golden.py).
    spec_dir = spec_dir or out_dir.parent / "hypotheses"
    spec_dir.mkdir(parents=True, exist_ok=True)
    for fam in spec["families"]:
        spec["families"][fam] = {arm: os.path.relpath(out_dir.resolve() / f, spec_dir.resolve())
                                 for arm, f in spec["families"][fam].items()}
    spec_path = spec_dir / f"h9_{dataset}.yaml"
    spec_path.write_text("# GENERATED by `fedastro h9-sweeps`: input of `fedastro hypotheses` (PREREG.md section 2).\n"
                         + yaml.safe_dump(spec, sort_keys=False))
    written.append(spec_path)
    return written


__all__ = ["emit_h9_sweeps", "SHIFT_SETTINGS", "PRIMARY_SHIFT", "SHIFTED_REGIONS", "EVAL_SEEDS"]
